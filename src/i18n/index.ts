const stored =
  typeof localStorage === 'undefined' ? null : localStorage.getItem('stilldue:language');
const initialPreference: LanguagePreference = isLanguagePreference(stored) ? stored : 'auto';

void i18n.use(initReactI18next).init({
  resources: Object.fromEntries(
    Object.entries(messages).map(([language, translation]) => [language, { translation }]),
  ),
  lng: resolveLanguage(initialPreference),
  fallbackLng: 'en',
  keySeparator: false,
  nsSeparator: false,
  interpolation: { escapeValue: false },
  returnNull: false,
});

export async function applyLanguage(preference: LanguagePreference) {
  const language = resolveLanguage(preference);
  setCurrentLanguage(language);
  if (typeof localStorage !== 'undefined') localStorage.setItem('stilldue:language', preference);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    document.documentElement.dir = languageDirection(language);
  }
  await i18n.changeLanguage(language);
}

void applyLanguage(initialPreference);
